// Copies the repository's Markdown documents into Starlight's content folder, so the Markdown files stay the only copy
// (ADR 0023, kept by ADR 0030). Run before every dev and build (see package.json). Nothing it writes is committed.
// It adds the front matter Starlight needs, takes the first heading as the page title, points links between documents at
// their pages and links to other repository files at GitHub, and fails when a relative link points at a file that is not
// in the repository, so a broken link stops the build instead of being published.
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BASE, DOCS, REPO } from './docs.mjs';

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Where a link found in `srcPath` should go on the site. A document that becomes a page links to its page, any other
 * repository file links to GitHub, a link to a file that is not in the repository throws.
 * @param {string} href
 * @param {string} srcPath  repository path of the document the link is in, for example 'docs/backup-format.md'
 * @param {{ slugBySrc: Record<string, string>, kindOf: (path: string) => 'file' | 'dir' | null }} ctx
 */
export function rewriteHref(href, srcPath, ctx) {
  if (href.startsWith('#')) return href;
  const [target, ...rest] = href.split('#');
  const fragment = rest.length ? `#${rest.join('#')}` : '';
  const github = new RegExp(`^${escapeRegExp(REPO)}/(?:blob|tree)/main/(.+)$`).exec(target);
  let path;
  if (github) {
    path = github[1].replace(/\/$/, '');
    if (!ctx.slugBySrc[path]) return href;
  } else if (/^[a-z][a-z0-9+.-]*:/i.test(target)) {
    return href;
  } else {
    path = posix.normalize(posix.join(posix.dirname(srcPath), target)).replace(/\/$/, '');
    if (path.startsWith('..')) throw new Error(`${srcPath}: link "${href}" leaves the repository`);
  }
  if (ctx.slugBySrc[path]) return `${BASE}/${ctx.slugBySrc[path]}/${fragment}`;
  const kind = ctx.kindOf(path);
  if (!kind) throw new Error(`${srcPath}: link "${href}" points at ${path}, which is not in the repository`);
  return `${REPO}/${kind === 'dir' ? 'tree' : 'blob'}/main/${path}${fragment}`;
}

/** Rewrites the targets of inline links `[text](target)`, leaving fenced code blocks alone. */
export function rewriteLinks(markdown, srcPath, ctx) {
  let fence = null;
  return markdown
    .split('\n')
    .map((line) => {
      const marker = /^\s*(```+|~~~+)/.exec(line);
      if (marker) {
        if (fence === null) fence = marker[1][0];
        else if (marker[1][0] === fence) fence = null;
        return line;
      }
      if (fence !== null) return line;
      return line.replace(/\]\(([^)\s]+)\)/g, (_whole, href) => `](${rewriteHref(href, srcPath, ctx)})`);
    })
    .join('\n');
}

/** One document to one Starlight page: front matter, no first heading (Starlight prints the title), links rewritten. */
export function toPage(doc, markdown, ctx) {
  const heading = /^# (.+)\n+/.exec(markdown);
  if (!heading) throw new Error(`${doc.src}: no first-level heading to use as the title`);
  const body = rewriteLinks(markdown.replace(heading[0], ''), doc.src, ctx);
  const front = [
    '---',
    `title: ${JSON.stringify(heading[1].trim())}`,
    `description: ${JSON.stringify(doc.description)}`,
    `editUrl: ${JSON.stringify(`${REPO}/edit/main/${doc.src}`)}`,
    '---',
    '',
    `<!-- Generated by apps/docs/scripts/sync-docs.mjs from ${doc.src}. Do not edit this file; edit the source. -->`,
    '',
  ].join('\n');
  return `${front}\n${body}`;
}

/** All pages, as { 'install.md': '---…' }. Throws on a broken link. */
export function buildPages(readText, kindOf) {
  const ctx = { slugBySrc: Object.fromEntries(DOCS.map((doc) => [doc.src, doc.slug])), kindOf };
  return Object.fromEntries(DOCS.map((doc) => [`${doc.slug}.md`, toPage(doc, readText(doc.src), ctx)]));
}

function main() {
  const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
  const outDir = join(repoRoot, 'apps', 'docs', 'src', 'content', 'docs');
  const kindOf = (path) => (existsSync(join(repoRoot, path)) ? (statSync(join(repoRoot, path)).isDirectory() ? 'dir' : 'file') : null);
  const pages = buildPages((path) => readFileSync(join(repoRoot, path), 'utf8'), kindOf);
  mkdirSync(outDir, { recursive: true });
  for (const [name, content] of Object.entries(pages)) writeFileSync(join(outDir, name), content);
  console.log(`Synced ${Object.keys(pages).length} documents into apps/docs/src/content/docs`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
